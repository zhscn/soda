#!/usr/bin/env bash
# Imports TextMate grammars and language configurations from a pinned VS Code
# release into grammars/, then regenerates src/syntax/bundled.rs. Upgrading
# means changing VSCODE_REF, rerunning, reviewing the diff and running tests.
set -euo pipefail

VSCODE_REF=1.144.0
# VS Code extension directory, then the language ids to keep from it.
EXTENSIONS=(
  "diff diff"
  "go go"
  "javascript javascript"
  "json json jsonc jsonl"
  "lua lua"
  "make makefile"
  "markdown-basics markdown"
  "python python"
  "rust rust"
  "shellscript shellscript"
  "typescript-basics typescript typescriptreact"
  "yaml yaml"
)

root=$(cd -- "$(dirname -- "$0")/.." && pwd)
out="$root/grammars"
base="https://raw.githubusercontent.com/microsoft/vscode/$VSCODE_REF"
staging=$(mktemp -d)
trap 'rm -rf "$staging"' EXIT

fetch() {
  curl -sfL --retry 3 -o "$2" "$1" || { echo "failed: $1" >&2; exit 1; }
}

fetch "$base/LICENSE.txt" "$staging/LICENSE.vscode.txt"
for entry in "${EXTENSIONS[@]}"; do
  read -r name languages <<<"$entry"
  dir="$staging/$name"
  mkdir -p "$dir"
  fetch "$base/extensions/$name/package.json" "$dir/package.full.json"
  curl -sfL -o "$dir/cgmanifest.json" "$base/extensions/$name/cgmanifest.json" || true
  # Keep the chosen languages, their configurations and every JSON grammar
  # they or other grammars may include; plist grammars are not supported.
  python3 -I - "$dir" $languages <<'EOF' >"$dir/files.txt"
import json, sys, os
directory, keep = sys.argv[1], set(sys.argv[2:])
package = json.load(open(os.path.join(directory, "package.full.json")))
contributes = package.get("contributes", {})
languages = [l for l in contributes.get("languages", []) if l["id"] in keep]
grammars = [
    g for g in contributes.get("grammars", [])
    if (g.get("language") in keep or g.get("language") is None)
    and g["path"].endswith(".json")
]
files = sorted({g["path"] for g in grammars} | {l["configuration"] for l in languages if l.get("configuration")})
manifest = {
    "name": package["name"],
    "languages": [
        {k: l[k] for k in ("id", "aliases", "extensions", "filenames", "configuration") if l.get(k)}
        for l in languages
    ],
    "grammars": [
        {k: g[k] for k in ("language", "scopeName", "path", "embeddedLanguages") if g.get(k)}
        for g in grammars
    ],
}
json.dump(manifest, open(os.path.join(directory, "package.json"), "w"), indent=1, sort_keys=True)
for f in files:
    print(os.path.normpath(f))
EOF
  rm "$dir/package.full.json"
  while read -r file; do
    mkdir -p "$dir/$(dirname "$file")"
    fetch "$base/extensions/$name/$file" "$dir/$file"
  done <"$dir/files.txt"
  rm "$dir/files.txt"
done

rm -rf "$out"
mv "$staging" "$out"
trap - EXIT
echo "$VSCODE_REF" >"$out/VERSION"

# Embed every imported file.
python3 -I - "$out" "$root/src/syntax/bundled.rs" <<'EOF'
import os, sys
out, target = sys.argv[1], sys.argv[2]
lines = [
    "//! Generated by scripts/import-grammars.sh; do not edit.",
    "",
    "pub(crate) struct Package {",
    "    pub name: &'static str,",
    "    pub manifest: &'static str,",
    "    pub files: &'static [(&'static str, &'static str)],",
    "}",
    "",
    "pub(crate) static PACKAGES: &[Package] = &[",
]
for name in sorted(os.listdir(out)):
    path = os.path.join(out, name)
    if not os.path.isdir(path):
        continue
    lines.append("    Package {")
    lines.append(f"        name: {name!r},".replace("'", '"'))
    lines.append(f'        manifest: include_str!("../../grammars/{name}/package.json"),')
    lines.append("        files: &[")
    for dirpath, _, filenames in sorted(os.walk(path)):
        for filename in sorted(filenames):
            relative = os.path.relpath(os.path.join(dirpath, filename), path)
            if relative in ("package.json", "cgmanifest.json"):
                continue
            lines.append(
                f'            ("{relative}", include_str!("../../grammars/{name}/{relative}")),'
            )
    lines.append("        ],")
    lines.append("    },")
lines.append("];")
open(target, "w").write("\n".join(lines) + "\n")
EOF
echo "imported VS Code $VSCODE_REF grammars into $out"
